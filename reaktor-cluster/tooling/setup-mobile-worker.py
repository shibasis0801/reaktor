#!/usr/bin/env python3
"""Prepare the existing offload workspace for physical Android and iOS flows."""
import hashlib
import json
import os
from pathlib import Path
import plistlib
import shlex
import shutil
import subprocess
import tarfile
import urllib.request


def run(*args, **kwargs):
    return subprocess.run(list(map(str, args)), check=True, **kwargs)


def main():
    root = Path.home() / 'dev/offload'
    state = root / '.remote-dev'
    config = json.loads((root / 'bestbuds/config/mobile-e2e.json').read_text())
    version = config['runnerVersion']
    destination = Path.home() / f'.gradle/dependeasy/tools/maestroRunner/{version}/darwin-arm64'
    binary = destination / 'bin/maestro-runner'
    checksum = config['runnerDarwinArm64Sha256']
    stamp = destination / '.sha256'
    if not binary.exists() or not stamp.exists() or stamp.read_text().strip() != checksum:
        if shutil.disk_usage(root).free < 16_000_000_000:
            raise SystemExit('Keep at least 15 GB free before installing the mobile runner')
        scratch = root / 'tmp/mobile-worker-setup'
        scratch.mkdir(parents=True, exist_ok=True)
        archive = scratch / 'runner.tar.gz'
        try:
            url = f'https://github.com/devicelab-dev/maestro-runner/releases/download/v{version}/maestro-runner-{version}-darwin-arm64.tar.gz'
            if not archive.exists():
                print(f'Downloading pinned Maestro runner {version}', flush=True)
                with urllib.request.urlopen(url, timeout=30) as response, archive.open('wb') as output:
                    shutil.copyfileobj(response, output)
            if hashlib.sha256(archive.read_bytes()).hexdigest() != checksum:
                raise SystemExit('Maestro runner checksum does not match the product pin')
            with tarfile.open(archive) as bundle:
                bundle.extractall(scratch, filter='data')
            destination.parent.mkdir(parents=True, exist_ok=True)
            if destination.exists():
                shutil.rmtree(destination)
            shutil.move(scratch / 'maestro-runner', destination)
            stamp.write_text(checksum)
        finally:
            shutil.rmtree(scratch)
    signing = root / 'bestbuds/config/apple-signing/development'
    keychain = signing / 'bestbuds-e2e.keychain-db'
    password = (signing / 'keychain-password.local').read_text().strip()
    # Keep credentials out of output, including security's verbose import output.
    run('security', 'unlock-keychain', '-p', password, keychain, capture_output=True)
    search = run('security', 'list-keychains', '-d', 'user', capture_output=True, text=True)
    keychains = shlex.split(search.stdout)
    if str(keychain) not in keychains:
        run('security', 'list-keychains', '-d', 'user', '-s', *keychains, keychain)
    run('security', 'set-keychain-settings', '-lut', '21600', keychain)
    run('security', 'set-key-partition-list', '-S', 'apple-tool:,apple:,codesign:', '-s', '-k', password,
        keychain, capture_output=True)
    for source in signing.glob('*.mobileprovision'):
        profile = plistlib.loads(run('security', 'cms', '-D', '-i', source, capture_output=True).stdout)
        for folder in ('Library/Developer/Xcode/UserData/Provisioning Profiles', 'Library/MobileDevice/Provisioning Profiles'):
            target = Path.home() / folder
            target.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, target / (profile['UUID'] + '.mobileprovision'))
    # Keep the global pinned tool pristine. Product signing belongs in a
    # workspace copy, just as it does in the shared DeviceFlow runner.
    runtime = root / 'bestbuds/tmp/dependeasy/mobile-worker/runner'
    shutil.copytree(destination, runtime, dirs_exist_ok=True,
                    ignore=shutil.ignore_patterns('cache', '._*', '.lock'))
    contract = runtime.parent / 'signing-contract.json'
    contract.write_text(json.dumps({'schema': 1, 'platform': 'ios',
        'team': config['appleTeamId'], 'wdaBundleId': config['wdaBundleId'],
        'runner': str(runtime / 'bin/maestro-runner')}))
    run('/opt/homebrew/bin/python3', root / 'bestbuds/scripts/prepare-ios-e2e.py',
        '--device-hook', 'beforeSuite', contract, 'true')
    binary = runtime / 'bin/maestro-runner'
    sdk = Path.home() / 'Library/Android/sdk'
    pnpm = Path.home() / '.gradle/dependeasy/tools/pnpm/12.10.1/darwin-arm64/bin'
    node = Path.home() / '.gradle/dependeasy/tools/node/24.21.0/darwin-arm64/bin'
    env = state / 'mobile-env.sh'
    env.write_text('\n'.join([
        '# Generated by tools/setup-mobile-worker.py; physical devices only.',
        f'export ANDROID_HOME={shlex.quote(str(sdk))}',
        'export ANDROID_SDK_ROOT="$ANDROID_HOME"',
        f'export PATH={shlex.quote(":".join(map(str, [sdk / "platform-tools", binary.parent, pnpm, node])))}:"$PATH"',
        'export REMOTE_DEV_WORKER=1',
        f'export REMOTE_DEV_MOBILE_HOOK={shlex.quote(str(state / "mobile-device-hook.py"))}',
        'export MAESTRO_AUTO_START_EMULATOR=false',
        f'export MAESTRO_TEAM_ID={shlex.quote(config["appleTeamId"])}',
        f'export MAESTRO_WDA_BUNDLE_ID={shlex.quote(config["wdaBundleId"])}',
        "/opt/homebrew/bin/python3 - <<'MOBILE_KEYCHAIN'",
        'from pathlib import Path',
        'import subprocess',
        f'directory = Path({str(signing)!r})',
        'subprocess.run(["security", "unlock-keychain", "-p", (directory / "keychain-password.local").read_text().strip(),',
        '                str(directory / "bestbuds-e2e.keychain-db")], check=True, capture_output=True)',
        'MOBILE_KEYCHAIN',
        '',
    ]))
    env.chmod(0o600)
    profile = Path.home() / '.zprofile'
    previous = profile.read_text() if profile.exists() else ''
    include = f'[ ! -f {shlex.quote(str(env))} ] || source {shlex.quote(str(env))}'
    if include not in previous:
        profile.write_text(previous.rstrip() + '\n\n# Physical mobile automation on this worker.\n' + include + '\n')
    # Native commands remain available in interactive worker terminals, too.
    local_bin = Path.home() / '.local/bin'
    local_bin.mkdir(parents=True, exist_ok=True)
    for name, target in {'adb': sdk / 'platform-tools/adb', 'maestro-runner': binary, 'pnpm': pnpm / 'pnpm'}.items():
        link = local_bin / name
        if link.is_symlink():
            link.unlink()
        if not link.exists():
            link.symlink_to(target)
    print(f'Installed and checksum-verified maestro-runner {version}')
    print('Registered development signing keychain and provisioning profiles')
    print(f'SSH environment: {env}')


if __name__ == '__main__':
    main()
